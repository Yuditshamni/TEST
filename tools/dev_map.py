"""Development map: writes DEV_MAP.md (Mermaid) from the database object files.

Folder: db/ (generic layout), or fabric/data/WH_DWH.Warehouse/ on Fabric (the first that holds .sql files).
The map is written next to it: db/DEV_MAP.md or fabric/data/DEV_MAP.md.

Boxes: tables and views in BRONZE / SILVER / GOLD (+ MNG when a load reads or writes it).
Arrows: a view reads FROM/JOIN; a procedure moves FROM/JOIN/USING -> INSERT INTO/MERGE INTO.
Dotted arrow: a read of another entity's SILVER/GOLD/MNG object (a dependency; see nogamy-db-objects, "Own lane").

Reads plain SQL text (FROM / JOIN / USING, INSERT INTO / MERGE INTO), so it works for most dialects.
Layer names: change LAYERS when the project uses other schema names.

    python tools/dev_map.py           # write the map
    python tools/dev_map.py --check   # exit 1 if the map is out of date (review)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUTS = [(ROOT / "db", ROOT / "db" / "DEV_MAP.md"),
           (ROOT / "fabric" / "data" / "WH_DWH.Warehouse", ROOT / "fabric" / "data" / "DEV_MAP.md")]
DB, OUT = next(((d, o) for d, o in LAYOUTS if d.is_dir() and any(d.rglob("*.sql"))), LAYOUTS[0])
PROCEDURE_FOLDERS = ("Procedures", "StoredProcedures")
LAYERS = ["BRONZE", "SILVER", "GOLD", "MNG"]

NAME = r"\[?(\w+)\]?\.\[?(\w+)\]?"
READ = re.compile(r"(?<!DELETE\s)\b(?:FROM|JOIN|USING)\s+" + NAME, re.I)
WRITE = re.compile(r"\b(?:INSERT\s+INTO|MERGE\s+INTO|MERGE)\s+" + NAME, re.I)
STATEMENT_END = re.compile(r"\b(?:COMMIT|END\s+TRY|TRUNCATE\s+TABLE|UPDATE)\b", re.I)


def strip_comments(sql):
    sql = re.sub(r"/\*.*?\*/", " ", sql, flags=re.S)
    return re.sub(r"--[^\n]*", " ", sql)


def full(m):
    return f"{m.group(1).upper()}.{m.group(2).upper()}"


def entity(obj):
    name = obj.split(".", 1)[1]
    name = re.sub(r"^TRY_", "", name)
    name = re.sub(r"^(V_|SP_|SILVER_|BRONZE_)", "", name)
    return re.sub(r"_(STEP\d+_\w+|FINAL_STEP)$", "", name)


def parse():
    nodes, edges = {}, set()  # nodes: obj -> kind; edges: (src, tgt, label)
    for path in sorted(DB.rglob("*.sql")):
        if len(path.relative_to(DB).parts) != 3:
            continue  # only <root>/<SCHEMA>/<Type>/<OBJECT>.sql
        schema, kind, name = path.parts[-3].upper(), path.parts[-2], path.stem.upper()
        obj = f"{schema}.{name}"
        sql = strip_comments(path.read_text(encoding="utf-8-sig"))
        if kind in ("Tables", "Views"):
            if schema in LAYERS[:3]:
                nodes[obj] = kind
            if kind == "Views":
                for m in READ.finditer(sql):
                    edges.add((full(m), obj, ""))
        elif kind in PROCEDURE_FOLDERS:
            # each write statement: its target, fed by the reads up to the end of the statement
            for w in WRITE.finditer(sql):
                rest = sql[w.end():]
                nxt = [p.start() for p in (WRITE.search(rest), STATEMENT_END.search(rest)) if p]
                segment = rest[: min(nxt)] if nxt else rest
                for m in READ.finditer(segment):
                    edges.add((full(m), full(w), name))
    keep = {(s, t, l) for s, t, l in edges
            if s != t and s.split(".")[0] in LAYERS and t.split(".")[0] in LAYERS}
    for s, t, _ in keep:
        nodes.setdefault(s, "Tables")
        nodes.setdefault(t, "Tables")
    return nodes, sorted(keep)


def node_id(obj):
    return obj.replace(".", "__")


def render(nodes, edges):
    lines = ["flowchart LR"]
    for layer in LAYERS:
        members = sorted(o for o in nodes if o.startswith(layer + "."))
        if not members:
            continue
        lines.append(f"  subgraph {layer}")
        for o in members:
            label = o.split(".", 1)[1]
            shape = f'(["{label}"])' if nodes[o] == "Views" else f'["{label}"]'
            lines.append(f"    {node_id(o)}{shape}")
        lines.append("  end")
    for s, t, label in edges:
        cross = s.split(".")[0] != "BRONZE" and entity(s) != entity(t)
        arrow = "-.->" if cross else "-->"
        text = f"|{label}|" if label else ""
        lines.append(f"  {node_id(s)} {arrow}{text} {node_id(t)}")
    tries = [node_id(o) for o in nodes if ".TRY_" in o]
    if tries:
        lines.append("  classDef try stroke-dasharray: 4 3")
        lines.append(f"  class {','.join(sorted(tries))} try")

    deps = [(s, t) for s, t, _ in edges if s.split(".")[0] != "BRONZE" and entity(s) != entity(t)]
    out = [
        "# DEV_MAP — development map of the database",
        "",
        f"Generated by `python tools/dev_map.py` from `{DB.relative_to(ROOT).as_posix()}/`. Do not edit by hand.",
        "",
        "Box = table · rounded = view · arrow = data flow (label = load procedure) · dotted = dependency on another entity · dashed border = `TRY_`.",
        "",
        "```mermaid",
        *lines,
        "```",
        "",
        "## Dependencies between entities",
        "",
    ]
    if deps:
        out += ["| Reads | Read by |", "|---|---|"] + [f"| `{s}` | `{t}` |" for s, t in deps]
    else:
        out.append("None.")
    return "\n".join(out) + "\n"


def main():
    text = render(*parse())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("DEV_MAP.md is out of date: run python tools/dev_map.py")
            sys.exit(1)
        print("DEV_MAP.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
